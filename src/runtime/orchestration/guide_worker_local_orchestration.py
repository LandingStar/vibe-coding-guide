def guide_worker_instruction_from_mapping(
    value: dict[str, Any],
    *,
    index: int | None = None,
) -> GuideWorkerInstruction:
    """Build a guide-worker instruction from MCP/JSON-style mapping input."""

    if not isinstance(value, dict):
        path = "workerInstructions"
        if index is not None:
            path = f"{path}[{index}]"
        raise ValueError(f"{path} must be an object")
    normalized = {
        _GUIDE_WORKER_INSTRUCTION_KEY_ALIASES.get(str(key), str(key)): item
        for key, item in value.items()
    }
    prefix = "workerInstructions"
    if index is not None:
        prefix = f"{prefix}[{index}]"

    def require_string(field: str) -> str:
        raw = normalized.get(field, "")
        if not isinstance(raw, str) or not raw.strip():
            raise ValueError(f"{prefix}.{field} must be a non-empty string")
        return raw.strip()

    def optional_string(field: str) -> str:
        raw = normalized.get(field, "")
        if raw in (None, ""):
            return ""
        if not isinstance(raw, str):
            raise ValueError(f"{prefix}.{field} must be a string when provided")
        return raw.strip()

    def string_tuple(field: str) -> tuple[str, ...]:
        raw = normalized.get(field, ())
        if raw in (None, ""):
            return ()
        if not isinstance(raw, (list, tuple)):
            raise ValueError(f"{prefix}.{field} must be a list of strings")
        items: list[str] = []
        for item_index, item in enumerate(raw):
            if not isinstance(item, str) or not item.strip():
                raise ValueError(
                    f"{prefix}.{field}[{item_index}] must be a non-empty string"
                )
            items.append(item.strip())
        return tuple(items)

    sandbox_profile = _sandbox_profile_from_mapping(
        normalized.get("sandbox_profile"),
        path=f"{prefix}.sandbox_profile",
        default_profile_id="shared-process",
    )

    return GuideWorkerInstruction(
        task_id=require_string("task_id"),
        title=require_string("title"),
        instruction=require_string("instruction"),
        lane_id=require_string("lane_id"),
        context_id=optional_string("context_id"),
        worker_agent_id=optional_string("worker_agent_id"),
        worker_runtime_provider=optional_string("worker_runtime_provider"),
        allowed_artifacts=string_tuple("allowed_artifacts"),
        acceptance=string_tuple("acceptance"),
        depends_on_task_ids=string_tuple("depends_on_task_ids"),
        output_artifact_id=optional_string("output_artifact_id"),
        sandbox_profile=sandbox_profile,
    )


def guide_worker_instructions_from_sequence(
    value: object,
) -> tuple[GuideWorkerInstruction, ...]:
    """Build guide-worker instructions from a JSON/MCP list payload."""

    if value in (None, ""):
        return ()
    if not isinstance(value, (list, tuple)):
        raise ValueError("workerInstructions must be a list of instruction objects")
    return tuple(
        guide_worker_instruction_from_mapping(item, index=index)
        for index, item in enumerate(value)
    )


