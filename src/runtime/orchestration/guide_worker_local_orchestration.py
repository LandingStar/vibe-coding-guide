@dataclass(frozen=True, slots=True)
class GuideWorkerLocalOrchestrationResult:
    """Compact result of one guide/worker local trajectory orchestration run."""

    request: GuideWorkerLocalOrchestrationRequest
    guide_artifact_id: str
    guide_artifact_version: str
    scheduler_artifact_id: str
    scheduler_artifact_version: str
    submitted_task_ids: tuple[str, ...]
    lane_ids: tuple[str, ...]
    parallel_waves: tuple[GuideWorkerParallelWave, ...]
    planned_worker_instructions: tuple[GuideWorkerInstruction, ...] = ()
    planning_source: str = "default_planner"
    wave_execution_results: tuple[GuideWorkerWaveExecutionResult, ...] = ()
    run_results: tuple[PreflightedTaskRunResult, ...] = ()
    final_state: SchedulerState = field(default_factory=SchedulerState)
    admission_result: dict[str, object] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return bool(self.submitted_task_ids) and all(
            self.final_state.tasks.get(task_id) is not None
            and self.final_state.tasks[task_id].state == "complete"
            for task_id in self.submitted_task_ids
        )

    def to_json_dict(self) -> dict[str, object]:
        task_states = {
            task_id: task.state
            for task_id, task in sorted(self.final_state.tasks.items())
        }
        run_task_ids = tuple(result.preflight.task.task_id for result in self.run_results)
        worker_runtime_providers = tuple(
            dict.fromkeys(
                self.final_state.tasks[task_id].agent.runtime_provider
                for task_id in self.submitted_task_ids
                if task_id in self.final_state.tasks
            )
        )
        runtime_provider = (
            worker_runtime_providers[0]
            if len(worker_runtime_providers) == 1
            else "mixed"
        )
        return {
            "ok": self.ok,
            "product_type": "guide_worker_local_trajectory_orchestration",
            "scenario": {
                "trajectory_id": self.request.trajectory_id,
                "guide_agent_id": self.request.guide_agent_id,
                "worker_agent_id": self.request.worker_agent_id,
                "runtime_provider": runtime_provider,
                "worker_runtime_providers": list(worker_runtime_providers),
                "parallelism_contract": "one_ready_worker_task_per_lane_per_wave",
                "execution_model": "scheduled_parallel_wave_sequential_fake_runtime",
            },
            "paths": {
                "artifact_store_path": str(self.request.artifact_store_path),
                "admission_ledger_path": str(self.request.admission_ledger_path),
                "snapshot_path": str(self.request.snapshot_path),
                "event_log_path": str(self.request.event_log_path),
            },
            "artifacts": {
                "guide_instruction": f"{self.guide_artifact_id}@{self.guide_artifact_version}",
                "scheduler_batch": f"{self.scheduler_artifact_id}@{self.scheduler_artifact_version}",
            },
            "submitted_task_ids": list(self.submitted_task_ids),
            "lane_ids": list(self.lane_ids),
            "parallel_waves": [wave.to_json_dict() for wave in self.parallel_waves],
            "planning": {
                "planner": self.request.planning_request.planner
                or "deterministic-lane-spec-v1",
                "source": self.planning_source,
                "leader_agent_id": self.request.guide_agent_id,
                "worker_count": len(self.planned_worker_instructions),
                "task_title": self.request.planning_request.task_title,
                "task_summary": self.request.planning_request.task_summary,
                "lane_spec_count": len(self.request.planning_request.lane_specs),
                "generated_instruction_count": len(self.planned_worker_instructions),
            },
            "planned_worker_instructions": [
                _instruction_to_payload(instruction, self.request)
                for instruction in self.planned_worker_instructions
            ],
            "wave_execution_results": [
                result.to_json_dict() for result in self.wave_execution_results
            ],
            "run_task_ids": list(run_task_ids),
            "task_states": task_states,
            "admission_result": dict(self.admission_result),
            "authority_split": {
                "guide_instruction_authority": "exchange_artifact_store",
                "task_lifecycle_authority": "scheduler_snapshot_and_event_log",
                "admission_authority": "exchange_artifact_admission_ledger",
                "parallel_wave_authority": "scheduler_ready_state_by_lane",
                "exchange_store_mutated": True,
                "scheduler_state_mutated": True,
                "admission_ledger_mutated": True,
                "provider_executed": bool(self.run_results),
                "runtime_provider": runtime_provider,
                "worker_runtime_providers": list(worker_runtime_providers),
                "true_process_parallelism": any(
                    result.mode == "threaded" and result.invoked_as_wave
                    for result in self.wave_execution_results
                ),
                "wave_executor_mode": self.request.wave_execution_mode,
                "scheduler_projection_refreshed": False,
                "local_work_trajectory_mutated": False,
                "raw_transcript_persisted": False,
            },
        }


