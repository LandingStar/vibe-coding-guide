def _validate_request(request: GuideWorkerLocalOrchestrationRequest) -> None:
    if not request.artifact_store_path:
        raise ValueError("guide/worker local orchestration requires artifact_store_path")
    if not request.admission_ledger_path:
        raise ValueError("guide/worker local orchestration requires admission_ledger_path")
    if not request.snapshot_path:
        raise ValueError("guide/worker local orchestration requires snapshot_path")
    if not request.event_log_path:
        raise ValueError("guide/worker local orchestration requires event_log_path")
    if not request.trajectory_id:
        raise ValueError("guide/worker local orchestration requires trajectory_id")
    if not request.guide_agent_id:
        raise ValueError("guide/worker local orchestration requires guide_agent_id")
    if not request.worker_agent_id:
        raise ValueError("guide/worker local orchestration requires worker_agent_id")
    if request.guide_agent_id == request.worker_agent_id:
        raise ValueError("guide/worker local orchestration requires distinct guide and worker agents")
    if not request.artifact_id_prefix:
        raise ValueError("guide/worker local orchestration requires artifact_id_prefix")
    if request.max_parallel_lanes < 1:
        raise ValueError("guide/worker local orchestration requires max_parallel_lanes >= 1")
    if request.max_waves < 1:
        raise ValueError("guide/worker local orchestration requires max_waves >= 1")


def _validate_instructions(
    request: GuideWorkerLocalOrchestrationRequest,
    instructions: tuple[GuideWorkerInstruction, ...],
) -> None:
    if not instructions:
        raise ValueError("guide/worker local orchestration requires at least one worker instruction")
    seen_task_ids: set[str] = set()
    for index, instruction in enumerate(instructions):
        prefix = f"worker_instructions[{index}]"
        if not instruction.task_id:
            raise ValueError(f"{prefix} requires task_id")
        if instruction.task_id in seen_task_ids:
            raise ValueError(f"duplicate worker task_id: {instruction.task_id!r}")
        seen_task_ids.add(instruction.task_id)
        if not instruction.title:
            raise ValueError(f"{prefix} requires title")
        if not instruction.instruction:
            raise ValueError(f"{prefix} requires instruction")
        if not instruction.lane_id:
            raise ValueError(f"{prefix} requires lane_id")
        for source_task_id in instruction.depends_on_task_ids:
            if source_task_id not in seen_task_ids:
                known = ", ".join(sorted(seen_task_ids)) or "(none)"
                raise ValueError(
                    f"{prefix} dependency {source_task_id!r} must refer to an earlier "
                    f"instruction task_id; known earlier tasks: {known}"
                )
        worker_agent_id = instruction.worker_agent_id or request.worker_agent_id
        if worker_agent_id == request.guide_agent_id:
            raise ValueError(f"{prefix} worker_agent_id must differ from guide_agent_id")
        runtime_provider = instruction.worker_runtime_provider or "fake"
        if runtime_provider not in {"fake", "qoder", "codex", "opencode"}:
            raise ValueError(
                f"{prefix} worker_runtime_provider must be 'fake', 'qoder', 'codex', "
                f"or 'opencode'; "
                f"got {runtime_provider!r}"
            )
