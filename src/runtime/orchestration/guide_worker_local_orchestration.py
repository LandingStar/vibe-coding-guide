def _mark_wave_tasks_running(
    state: SchedulerState,
    preflights: tuple[object, ...],
    *,
    event_log: SchedulerEventSink | None,
    timestamp: str,
) -> SchedulerState:
    tasks = dict(state.tasks)
    for preflight in preflights:
        task = preflight.task
        current = tasks.get(task.task_id)
        if current is None:
            raise ValueError(f"wave task {task.task_id!r} is missing from scheduler state")
        if current != task:
            raise ValueError(
                f"wave preflight bundle for task {task.task_id!r} "
                "does not match current scheduler state"
            )
        if current.state != "ready":
            raise ValueError(f"wave task {task.task_id!r} is not ready: {current.state}")
        tasks[task.task_id] = replace(current, state="running")
        _append_scheduler_event(
            event_log,
            event_kind="task_running",
            task_id=task.task_id,
            from_state="ready",
            to_state="running",
            timestamp=timestamp,
        )
    return replace(state, tasks=tasks)


def _invoke_wave_runtime_tasks(
    preflights: tuple[object, ...],
    *,
    runtime_registry: AgentRuntimeAdapterRegistry,
    mode: GuideWorkerWaveExecutionMode,
) -> tuple[GuideWorkerWaveTaskRun, ...]:
    if mode == "threaded" and len(preflights) > 1:
        with ThreadPoolExecutor(max_workers=len(preflights)) as executor:
            return tuple(
                executor.map(
                    lambda preflight: _invoke_wave_runtime_task(
                        preflight,
                        runtime_registry=runtime_registry,
                    ),
                    preflights,
                )
            )
    return tuple(
        _invoke_wave_runtime_task(preflight, runtime_registry=runtime_registry)
        for preflight in preflights
    )


def _invoke_wave_runtime_task(
    preflight: object,
    *,
    runtime_registry: AgentRuntimeAdapterRegistry,
) -> GuideWorkerWaveTaskRun:
    task = preflight.task
    try:
        runtime = runtime_registry.get(task.agent.runtime_provider)
        session = runtime.start_session(task.agent)
        result = runtime.run_task(session, preflight.runtime_task)
        return GuideWorkerWaveTaskRun(
            task_id=task.task_id,
            lane_id=task.context_scope.lane_id,
            runtime_result=result,
        )
    except Exception as exc:
        return GuideWorkerWaveTaskRun(
            task_id=task.task_id,
            lane_id=task.context_scope.lane_id,
            error=str(exc) or type(exc).__name__,
        )


def _merge_wave_task_success(
    state: SchedulerState,
    task_run: GuideWorkerWaveTaskRun,
    *,
    event_log: SchedulerEventSink | None,
    timestamp: str,
) -> SchedulerState:
    result = task_run.runtime_result
    if result is None:
        raise ValueError(f"cannot merge missing runtime result for task {task_run.task_id!r}")
    running = state.tasks[task_run.task_id]
    output_ref = ExchangeReference(
        ref_kind="exchange_artifact",
        ref_id=result.output_artifact.artifact_id,
        version=result.output_artifact.version,
    )
    next_state = "review_required" if result.permission_requests else "complete"
    blocked_reason = _permission_review_reason(result.permission_requests)
    completed = replace(
        running,
        state=next_state,
        blocked_reason=blocked_reason,
        run_id=result.run_handle.run_id,
        output_artifact_ref=output_ref,
    )
    tasks = dict(state.tasks)
    tasks[task_run.task_id] = completed
    run_record = TaskRunRecord(
        task_id=task_run.task_id,
        run_id=result.run_handle.run_id,
        session_id=result.run_handle.session_id,
        output_artifact_id=result.output_artifact.artifact_id,
        output_artifact_version=result.output_artifact.version,
        state=next_state,
    )
    updated = replace(state, tasks=tasks, run_records=state.run_records + (run_record,))
    _append_scheduler_event(
        event_log,
        event_kind="task_review_required" if result.permission_requests else "task_completed",
        task_id=task_run.task_id,
        from_state="running",
        to_state=next_state,
        reason=blocked_reason,
        run_id=result.run_handle.run_id,
        session_id=result.run_handle.session_id,
        output_artifact_id=result.output_artifact.artifact_id,
        output_artifact_version=result.output_artifact.version,
        related_artifact_ids=(result.output_artifact.artifact_id,),
        timestamp=timestamp,
    )
    return updated


def _merge_wave_task_failure(
    state: SchedulerState,
    task_run: GuideWorkerWaveTaskRun,
    *,
    event_log: SchedulerEventSink | None,
    timestamp: str,
) -> SchedulerState:
    reason = _runtime_failure_reason(task_run.error)
    failed = replace(
        state.tasks[task_run.task_id],
        state="blocked",
        blocked_reason=reason,
    )
    tasks = dict(state.tasks)
    tasks[task_run.task_id] = failed
    updated = replace(state, tasks=tasks)
    _append_scheduler_event(
        event_log,
        event_kind="task_run_failed",
        task_id=task_run.task_id,
        from_state="running",
        to_state="blocked",
        reason=reason,
        timestamp=timestamp,
    )
    return updated


def _append_scheduler_event(
    event_log: SchedulerEventSink | None,
    *,
    event_kind: str,
    task_id: str,
    from_state: str,
    to_state: str,
    timestamp: str,
    reason: str = "",
    run_id: str = "",
    session_id: str = "",
    output_artifact_id: str = "",
    output_artifact_version: str = "",
    related_artifact_ids: tuple[str, ...] = (),
) -> None:
    if event_log is None:
        return
    sequence = len(event_log.read_all()) + 1
    event_log.append(
        SchedulerEvent(
            event_id=f"scheduler-event-{sequence}",
            event_kind=event_kind,
            timestamp=timestamp,
            task_id=task_id,
            from_state=from_state,
            to_state=to_state,
            reason=reason,
            run_id=run_id,
            session_id=session_id,
            output_artifact_id=output_artifact_id,
            output_artifact_version=output_artifact_version,
            related_artifact_ids=related_artifact_ids,
            sequence=sequence,
        )
    )


def _permission_review_reason(permission_requests: tuple[object, ...]) -> str:
    if not permission_requests:
        return ""
    if len(permission_requests) == 1:
        request = permission_requests[0]
        return f"permission review required: {request.request_kind} {request.target}".rstrip()
    return f"permission review required: {len(permission_requests)} requests"


def _runtime_failure_reason(reason: str) -> str:
    prefix = "runtime failure: "
    return reason if reason.startswith(prefix) else f"{prefix}{reason}"


